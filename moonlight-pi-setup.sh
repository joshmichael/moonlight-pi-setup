# Keep a copy of this script so --uninstall works even if it was run with curl | bash.
save_script_copy() {
  local src="${BASH_SOURCE[0]:-}"
  if [[ -n $src && -f $src ]]; then
    if [[ $(readlink -f "$src") != $(readlink -f "$SAVED_SCRIPT" 2>/dev/null || true) ]]; then
      cp "$src" "$SAVED_SCRIPT"
    fi
  elif ! curl -fsSL "$RAW_SCRIPT_URL" -o "$SAVED_SCRIPT"; then
    warn "Could not save a copy of this script for uninstalling. Download it again from ${REPO_URL} if needed."
    return 0
  fi
  chmod +x "$SAVED_SCRIPT"
}

