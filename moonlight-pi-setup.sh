on_error() {
  local line=$1
  error "Something went wrong (line ${line})."
  if [[ -n "${LOG_FILE:-}" ]]; then
    error "A full log of this run is saved at: ${LOG_FILE}"
  fi
  error "If you think this is a bug, please report it at: ${ISSUES_URL}"
}
trap 'on_error $LINENO' ERR

cleanup() {
  if [[ -n "${SUDO_KEEPALIVE_PID}" ]]; then
    kill "${SUDO_KEEPALIVE_PID}" 2>/dev/null || true
  fi
  if [[ -n $MENU_SRC ]]; then
    rm -rf "$MENU_SRC"
  fi
  # Run as root by the TV menu's updates: give the user back their files.
  if (( EUID == 0 )) && [[ -n ${MOONLIGHT_PI_USER:-} ]]; then
    local d
    for d in "$STATE_DIR" "$CONFIG_DIR"; do
      [[ -e $d ]] && chown -R "${USER_NAME}:" "$d"
    done
    for d in "$BASH_PROFILE" "$ASOUNDRC" "${HOME}/.local" "${HOME}/.local/share" "${HOME}/.config"; do
      [[ -e $d ]] && chown "${USER_NAME}:" "$d"
    done
  fi
  return 0
}
trap cleanup EXIT

# as_user <command...>: run as the Pi's user (this script runs as root for the
# TV menu's updates).
as_user() {
  if (( EUID == 0 )); then
    runuser -u "$USER_NAME" -- env HOME="$HOME" "$@"
  else
    "$@"
  fi
}

# Read a line from the terminal, even when the script is piped into bash.
read_tty() {
  local __var=$1 __reply=""
  if ! read -r __reply < /dev/tty; then
    __reply=""
  fi
  printf -v "$__var" '%s' "$__reply"
}

# ask_yes_no "Question" y|n   -> returns 0 for yes, 1 for no (the default when unattended)
ask_yes_no() {
  local prompt=$1 default=$2 hint reply
  if (( UNATTENDED )); then
    [[ $default == y ]]
    return
  fi
  if [[ $default == y ]]; then hint="[Y/n]"; else hint="[y/N]"; fi
  while true; do
    printf '%s %s ' "$prompt" "$hint"
    read_tty reply
    reply=${reply:-$default}
    case "${reply,,}" in
      y|yes) return 0 ;;
      n|no)  return 1 ;;
      *)     echo "    Please answer y or n." ;;
    esac
  done
}

# ---------------------------------------------------------------------------
# State and backups
# ---------------------------------------------------------------------------
state_set() {
  local key=$1 value=$2
  mkdir -p "$STATE_DIR"
  touch "$STATE_FILE"
  grep -v "^${key}=" "$STATE_FILE" > "${STATE_FILE}.tmp" || true
  printf '%s=%s\n' "$key" "$value" >> "${STATE_FILE}.tmp"
  mv "${STATE_FILE}.tmp" "$STATE_FILE"
}

state_unset() {
  [[ -f $STATE_FILE ]] || return 0
  grep -v "^${1}=" "$STATE_FILE" > "${STATE_FILE}.tmp" || true
  mv "${STATE_FILE}.tmp" "$STATE_FILE"
}

state_get() {
  local key=$1 content
  [[ -f $STATE_FILE ]] || return 0
  content=$(<"$STATE_FILE")
  grep -m1 "^${key}=" <<<"$content" | cut -d= -f2- || true
}

# previous_choice <state key> <default y|n> -- the answer from the last run, so
# that re-running the script to change one setting keeps the others as they were.
previous_choice() {
  case "$(state_get "$1")" in
    1) echo y ;;
    0) echo n ;;
    *) echo "$2" ;;
  esac
}

# backup_file <path> [sudo]
backup_file() {
  local file=$1 use_sudo=${2:-} dest
  [[ -e $file ]] || return 0
  mkdir -p "$BACKUP_DIR"
  dest="${BACKUP_DIR}/$(basename "$file").$(date +%Y%m%d-%H%M%S).bak"
  if [[ -n $use_sudo ]]; then
    sudo cp -a "$file" "$dest"
    sudo chown "${USER_NAME}:" "$dest"
  else
    cp -a "$file" "$dest"
  fi
  info "Backed up ${file} to ${dest}"
}

# remove_block <file> [sudo] -- removes the section between our marker comments
remove_block() {
  local file=$1 use_sudo=${2:-} tmp
  [[ -f $file ]] || return 0
  tmp=$(mktemp)
  awk -v b="$MARK_BEGIN" -v e="$MARK_END" \
    '$0==b {skip=1; next} $0==e {skip=0; next} !skip' "$file" > "$tmp"
  if [[ -n $use_sudo ]]; then
    # shellcheck disable=SC2024  # the temp file is ours; only the write needs sudo
    sudo tee "$file" < "$tmp" > /dev/null
  else
    cat "$tmp" > "$file"
  fi
  rm -f "$tmp"
}

# Was ~/.asoundrc written by this script?
asoundrc_is_ours() {
  local first=""
  [[ -f $ASOUNDRC ]] || return 1
  IFS= read -r first < "$ASOUNDRC" || true
  [[ $first == "${ASOUND_HEADER}"* ]]
}

package_installed() {
  local status
  status=$(dpkg-query -W -f='${Status}' "$1" 2>/dev/null || true)
  [[ $status == "install ok installed" ]]
}

# ---------------------------------------------------------------------------
# Detection
# ---------------------------------------------------------------------------
detect_display_device() {
  local link target card driver
  for link in /dev/dri/by-path/*-card; do
    [[ -e $link ]] || continue
    target=$(readlink -f "$link")
    card=$(basename "$target")
    driver=$(basename "$(readlink -f "/sys/class/drm/${card}/device/driver" 2>/dev/null)" 2>/dev/null || true)
    if [[ $driver == "vc4-drm" ]]; then
      printf '%s' "$link"
      return 0
    fi
  done
  # Fallback: the Pi 5 display controller is normally called platform-axi:gpu-card
  for link in /dev/dri/by-path/*gpu-card; do
    if [[ -e $link ]]; then
      printf '%s' "$link"
      return 0
    fi
  done
  return 1
}

hdmi_connected() {
  local connector=$1 f
  for f in /sys/class/drm/card*-"${connector}"/status; do
    if [[ -r $f ]] && [[ $(<"$f") == "connected" ]]; then
      return 0
    fi
  done
  return 1
}

# Is the desktop version of Raspberry Pi OS installed (rather than Lite)? Still
# true after switching the Pi to boot to the console, as the display manager remains.
desktop_installed() {
  [[ $(systemctl get-default 2>/dev/null || true) == "graphical.target" ]] \
    || [[ -e /etc/systemd/system/display-manager.service ]]
}

# How the Pi currently boots, using raspi-config's names:
#   B1 console, B2 console with auto-login, B3 desktop, B4 desktop with auto-login
# (B3 and B4 only on the desktop version, installed with --force)
current_boot_behaviour() {
  if [[ $(systemctl get-default 2>/dev/null || true) == "graphical.target" ]]; then
    if grep -qs '^autologin-user=' "$LIGHTDM_CONF"; then echo B4; else echo B3; fi
  else
    if [[ -f $AUTOLOGIN_DROPIN ]]; then echo B2; else echo B1; fi
  fi
}

boot_behaviour_name() {
  case "$1" in
    B1) echo "console login" ;;
    B2) echo "console with automatic login" ;;
    B3) echo "desktop" ;;
    B4) echo "desktop with automatic login" ;;
    *)  echo "unknown" ;;
  esac
}

virtualhere_installed() {
  local units
  units=$(systemctl list-unit-files 2>/dev/null || true)
  grep -qi virtualhere <<<"$units"
}

# ---------------------------------------------------------------------------
# Pre-flight checks
# ---------------------------------------------------------------------------
check_failed() {
  if (( FORCE )); then
    warn "$* (continuing because --force was used)"
  else
    die "$* Use --force to continue anyway (unsupported)."
  fi
}

preflight() {
  step "Checking your system"

  command -v sudo > /dev/null 2>&1 || die "sudo is not installed."
  if [[ $EUID -eq 0 ]]; then
    # Only the TV menu's updates run this as root, and they say for which user.
    if [[ -z ${MOONLIGHT_PI_USER:-} ]] || (( ! UNATTENDED )); then
      die "Please run this script as your normal user (without sudo). It will ask for your password when needed."
    fi
    getent passwd "$USER_NAME" > /dev/null || die "No such user: ${USER_NAME}"
  else
    info "Some steps need administrator access, so you may be asked for your password."
    # Only prompt for a password if sudo actually needs one.
    sudo -n true 2>/dev/null || sudo -v || die "Could not get administrator access."
    ( while true; do sudo -n true; sleep 50; kill -0 "$$" 2>/dev/null || exit; done ) 2>/dev/null &
    SUDO_KEEPALIVE_PID=$!
  fi
  # An install that needed --force (for example on the desktop version) is
  # updated the same way.
  if [[ $(state_get forced) == 1 ]] && (( UNATTENDED )); then
    FORCE=1
  fi

  # Hardware
  local model=""
  if [[ -r /proc/device-tree/model ]]; then
    model=$(tr -d '\0' < /proc/device-tree/model)
  fi
  if [[ $model == *"Raspberry Pi 5"* || $model == *"Raspberry Pi 500"* || $model == *"Compute Module 5"* ]]; then
    ok "Hardware: ${model}"
  else
    check_failed "This script supports the Raspberry Pi 5 only (detected: ${model:-unknown})."
  fi

  # Architecture
  local arch
  arch=$(dpkg --print-architecture)
  if [[ $arch == "arm64" ]]; then
    ok "64-bit operating system"
  else
    check_failed "A 64-bit operating system is required (detected: ${arch})."
  fi

  # OS version
  # shellcheck disable=SC1091
  OS_CODENAME=$(. /etc/os-release && printf '%s' "${VERSION_CODENAME:-unknown}")
  if [[ $OS_CODENAME == "trixie" ]]; then
    ok "Raspberry Pi OS (Trixie)"
  else
    check_failed "This script is written for Raspberry Pi OS based on Trixie (detected: ${OS_CODENAME})."
  fi

  # Lite only: Moonlight runs on its own on the TV, without a desktop.
  if desktop_installed; then
    check_failed "This script is for Raspberry Pi OS Lite (64-bit), but this is the desktop version. Please install Raspberry Pi OS Lite (64-bit) with Raspberry Pi Imager."
  else
    ok "Raspberry Pi OS Lite"
  fi

  # Display controller
  if DISPLAY_DEVICE=$(detect_display_device); then
    ok "Display controller: ${DISPLAY_DEVICE}"
  else
    check_failed "Could not find the Pi's display controller under /dev/dri/by-path."
    DISPLAY_DEVICE="/dev/dri/by-path/platform-axi:gpu-card"
  fi

  # HDMI port
  if hdmi_connected HDMI-A-1; then
    HDMI_PORT=0
    ok "TV detected on HDMI 0 (the port next to the USB-C power socket)"
  elif hdmi_connected HDMI-A-2; then
    HDMI_PORT=1
    ok "TV detected on HDMI 1"
  elif (( UNATTENDED )); then
    HDMI_PORT=$(state_get hdmi_port)
    [[ $HDMI_PORT == 1 ]] || HDMI_PORT=0
  else
    warn "No TV detected on either HDMI port. Is the TV switched on?"
    printf '    Which HDMI port will the TV use? 0 = next to the power socket, 1 = the other one [0]: '
    local reply
    read_tty reply
    if [[ $reply == "1" ]]; then HDMI_PORT=1; else HDMI_PORT=0; fi
  fi
  if ! grep -q "vc4hdmi${HDMI_PORT}" /proc/asound/cards 2>/dev/null; then
    warn "HDMI audio device vc4hdmi${HDMI_PORT} was not found. Audio may not work until the TV is connected and the Pi is rebooted."
  fi

  # Network: ask the kernel which interface it would use to reach the internet,
  # which picks the right one when both Ethernet and Wi-Fi are connected.
  local iface speed duplex
  iface=$(ip route get 1.1.1.1 2>/dev/null \
    | awk '{for (i = 1; i < NF; i++) if ($i == "dev") {print $(i + 1); exit}}' || true)
  if [[ -z $iface ]]; then
    iface=$(ip -o route show default 2>/dev/null \
      | awk '{for (i = 1; i < NF; i++) if ($i == "dev") {print $(i + 1); exit}}' || true)
  fi
  if [[ -z $iface ]]; then
    die "No network connection detected. This script needs internet access."
  elif [[ -d /sys/class/net/${iface}/wireless || $iface == wl* ]]; then
    warn "You're connected over Wi-Fi (${iface}). Wired Ethernet is strongly recommended for streaming."
  else
    speed=$(cat "/sys/class/net/${iface}/speed" 2>/dev/null || true)
    duplex=$(cat "/sys/class/net/${iface}/duplex" 2>/dev/null || true)
    if [[ $speed =~ ^[0-9]+$ ]] && (( speed >= 1000 )) && [[ $duplex == "full" ]]; then
      ok "Wired network: ${speed} Mb/s, full duplex"
    else
      warn "Your wired connection is running at ${speed:-unknown} Mb/s, ${duplex:-unknown} duplex."
      warn "Gigabit (1000 Mb/s, full duplex) is expected. Check the cable and your router or switch."
    fi
  fi
}

