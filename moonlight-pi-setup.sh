usage() {
  cat <<EOF
moonlight-pi-setup ${SCRIPT_VERSION}

Sets up a Raspberry Pi 5 running Raspberry Pi OS (64-bit, Trixie; Lite or
desktop) as a Moonlight game-streaming client.

Usage: $0 [option]

  (no option)    Install, or re-run to change your settings
  --uninstall    Undo the changes this script made
  --force        Skip the hardware and OS checks (unsupported)
  --help         Show this help
  --version      Show the version

More information: ${REPO_URL}
EOF
}

main() {
  local mode="install"
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --uninstall) mode="uninstall" ;;
      --force)     FORCE=1 ;;
      --help|-h)   usage; exit 0 ;;
      --version)   echo "$SCRIPT_VERSION"; exit 0 ;;
      *)           usage; exit 1 ;;
    esac
    shift
  done

  mkdir -p "$STATE_DIR"
  LOG_FILE="${STATE_DIR}/${mode}-$(date +%Y%m%d-%H%M%S).log"
  exec > >(tee -a "$LOG_FILE") 2>&1

  printf '%sMoonlight Pi Setup %s%s\n' "$C_BOLD" "$SCRIPT_VERSION" "$C_RESET"

  if [[ $mode == "uninstall" ]]; then
    do_uninstall
    exit 0
  fi

  preflight
  ask_questions
  install_base_packages
  install_moonlight
  setup_groups
  setup_display
  setup_audio
  setup_network
  setup_autologin
  setup_bash_profile
  setup_quiet_boot
  setup_quit_on_shutdown
  install_tailscale
  install_virtualhere
  finish_install
}

