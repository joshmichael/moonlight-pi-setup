# Copy the menu files and the settings helper from next to this script (a git
# checkout), or download them, into MENU_SRC.
fetch_menu_files() {
  local src_dir="" f
  if [[ -n ${BASH_SOURCE[0]:-} && -f ${BASH_SOURCE[0]} ]]; then
    src_dir="$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/menu"
  fi
  MENU_SRC=$(mktemp -d)
  chmod 755 "$MENU_SRC"
  for f in "${MENU_FILES[@]}"; do
    if [[ -n $src_dir && -f $src_dir/$f ]]; then
      cp "$src_dir/$f" "$MENU_SRC/$f"
    elif ! curl -fsSL "${MENU_BASE_URL}/${f}" -o "$MENU_SRC/$f"; then
      die "Could not download the TV menu (${f}). Check the internet connection and run this script again."
    fi
  done
  chmod 644 "$MENU_SRC"/*
}

# Keep the current settings on a re-run (they may have been changed on the TV).
# A first install uses the recommended ones until Quick setup on the TV.
load_settings() {
  if [[ -z $(state_get version) ]]; then
    FIRST_INSTALL=1
    return 0
  fi
  # What older versions of this script saved, in case the helper can't tell.
  local key value vh=0
  value=$(state_get audio_mode)
  if [[ $value =~ ^(stereo|5\.1|7\.1)$ ]]; then AUDIO_MODE=$value; fi
  [[ $(state_get quiet_boot) == 0 ]] && OPT_QUIET_BOOT=0
  [[ $(state_get quit_on_shutdown) == 0 ]] && OPT_QUIT_ON_SHUTDOWN=0
  [[ $(state_get wifi_powersave_off) == 0 ]] && OPT_WIFI_POWERSAVE_OFF=0
  [[ $(state_get usb_handoff) == 0 ]] && OPT_USB_HANDOFF=0
  # What the Pi is actually set to.
  while IFS='=' read -r key value; do
    case "$key" in
      speakers)
        if [[ $value =~ ^(stereo|5\.1|7\.1)$ ]]; then AUDIO_MODE=$value; fi ;;
      quiet_boot) OPT_QUIET_BOOT=$value ;;
      quit_on_shutdown) OPT_QUIT_ON_SHUTDOWN=$value ;;
      wifi_powersave) OPT_WIFI_POWERSAVE_OFF=$(( value == 1 ? 0 : 1 )) ;;
      virtualhere) vh=$value ;;
      usb_handoff) OPT_USB_HANDOFF=$value ;;
    esac
  done < <(as_user bash "${MENU_SRC}/moonlight-settings.sh" status 2>/dev/null || true)
  # VirtualHere installed now for the first time: use the recommended setting.
  if (( ! vh )); then
    OPT_USB_HANDOFF=1
  fi
  return 0
}

ask_questions() {
  step "Setup options"
  # Wi-Fi only works once the Pi knows which country's channels it may use.
  if (( ! UNATTENDED )) && compgen -G '/sys/class/net/*/wireless' > /dev/null; then
    local country=""
    country=$(sudo raspi-config nonint get_wifi_country 2>/dev/null || true)
    if [[ ! $country =~ ^[A-Z]{2}$ ]]; then
      while true; do
        printf '    Which country are you in? Wi-Fi needs this to use the right channels\n'
        printf '    (two letters, for example GB, US, DE, AU): '
        read_tty country
        country=${country^^}
        [[ $country =~ ^[A-Z]{2}$ ]] && break
        echo "    Please enter a two-letter country code."
      done
      WIFI_COUNTRY=$country
    fi
  fi

  if (( ! UNATTENDED )); then
    if command -v tailscale > /dev/null 2>&1; then
      info "Tailscale is already installed. Skipping that question."
    elif ask_yes_no "    Install Tailscale, to stream when you're away from home?" n; then
      OPT_TAILSCALE=1
    fi
    if virtualhere_installed; then
      info "VirtualHere is already installed. Skipping that question."
    elif ask_yes_no "    Install VirtualHere, to share USB devices plugged into the Pi with your PC?" n; then
      OPT_VIRTUALHERE=1
    fi
  fi

  step "Summary"
  info "Moonlight:        install the official moonlight-qt package, and start it when the Pi boots"
  info "TV menu:          controllers, Wi-Fi, settings and power, when Moonlight closes"
  if [[ -n $WIFI_COUNTRY ]]; then
    info "Wi-Fi country:    ${WIFI_COUNTRY}"
  fi
  if command -v tailscale > /dev/null 2>&1; then
    info "Tailscale:        already installed"
  else
    info "Tailscale:        $( (( OPT_TAILSCALE )) && echo yes || echo no)"
  fi
  if virtualhere_installed; then
    info "VirtualHere:      already installed"
  else
    info "VirtualHere:      $( (( OPT_VIRTUALHERE )) && echo yes || echo no)"
  fi
  echo
  if (( FIRST_INSTALL )); then
    info "Settings (recommended for now; after the restart, Quick setup on the TV asks about them):"
  else
    info "Your settings are kept (change them on the TV, in the menu's Settings):"
  fi
  info "  Speakers:           ${AUDIO_MODE}"
  info "  Quit game on PC:    $( (( OPT_QUIT_ON_SHUTDOWN )) && echo "yes, when the Pi shuts down" || echo no)"
  info "  Hide boot messages: $( (( OPT_QUIET_BOOT )) && echo yes || echo no)"
  info "  Wi-Fi power saving: $( (( OPT_WIFI_POWERSAVE_OFF )) && echo off || echo on)"
  if (( OPT_VIRTUALHERE )) || virtualhere_installed; then
    info "  Share USB devices:  $( (( OPT_USB_HANDOFF )) && echo "only while streaming" || echo "all the time")"
  fi
  echo
  ask_yes_no "    Go ahead?" y || die "Cancelled. Nothing was changed."
}

# ---------------------------------------------------------------------------
# Installation steps
# ---------------------------------------------------------------------------
install_base_packages() {
  step "Installing required packages"
  sudo apt-get update
  sudo apt-get install -y curl alsa-utils
  ok "Base packages installed"
}

install_moonlight() {
  step "Installing Moonlight"
  local policy
  policy=$(apt-cache policy moonlight-qt 2>/dev/null || true)
  if grep -q 'Candidate: [0-9]' <<<"$policy"; then
    info "moonlight-qt is available from your existing package sources."
  else
    info "Adding the official Moonlight package repository..."
    curl -1sLf "$MOONLIGHT_REPO_SCRIPT" | distro=raspbian codename="$OS_CODENAME" sudo -E bash
    state_set moonlight_repo_added 1
    sudo apt-get update
  fi
  sudo apt-get install -y moonlight-qt
  ok "Moonlight installed: $(dpkg-query -W -f='${Version}' moonlight-qt)"
}

setup_groups() {
  step "Giving your user access to the display, GPU, input and audio devices"
  sudo usermod -aG video,render,input,audio "$USER_NAME"
  ok "Added ${USER_NAME} to the video, render, input and audio groups"
}

setup_display() {
  step "Configuring the display"
  mkdir -p "$CONFIG_DIR"
  cat > "$EGLFS_CONFIG" <<EOF
{
  "device": "${DISPLAY_DEVICE}"
}
EOF
  ok "Moonlight's interface will use ${DISPLAY_DEVICE}"
}

# Remove our ~/.asoundrc and put back the user's original, if they had one.
remove_asoundrc() {
  asoundrc_is_ours || return 0
  rm -f "$ASOUNDRC"
  local original
  original=$(state_get asoundrc_original)
  if [[ -n $original && -f $original ]]; then
    cp -a "$original" "$ASOUNDRC"
    ok "Restored your original ${ASOUNDRC}"
  else
    ok "Removed ${ASOUNDRC}"
  fi
}

setup_audio() {
  step "Setting the speakers to ${AUDIO_MODE}"
  if [[ -f $ASOUNDRC ]] && ! asoundrc_is_ours; then
    # A file we didn't create: keep a copy so --uninstall can put it back.
    mkdir -p "$BACKUP_DIR"
    local dest="${BACKUP_DIR}/asoundrc.original"
    if [[ ! -f $dest ]]; then
      cp -a "$ASOUNDRC" "$dest"
      state_set asoundrc_original "$dest"
      info "Backed up your existing ${ASOUNDRC} to ${dest}"
    else
      backup_file "$ASOUNDRC"
    fi
  fi
  state_set hdmi_port "$HDMI_PORT"
  as_user "$SETTINGS_HELPER" speakers "$AUDIO_MODE" | sed 's/^/    /'
  ok "Wrote ${ASOUNDRC}, and set Moonlight's audio setting to match"
}

setup_network() {
  step "Tuning the network for streaming"
  printf '%s\n%s\n' \
    "# Added by moonlight-pi-setup: allow larger UDP receive buffers for game streaming" \
    "net.core.rmem_max=33554432" | sudo tee "$SYSCTL_FILE" > /dev/null
  sudo sysctl -p "$SYSCTL_FILE" > /dev/null
  ok "Raised the network receive buffer limit (net.core.rmem_max)"
  if compgen -G '/sys/class/net/*/wireless' > /dev/null || [[ -f $NM_WIFI_CONF ]]; then
    helper wifi-powersave "$( (( OPT_WIFI_POWERSAVE_OFF )) && echo off || echo on)"
  fi
}

setup_autologin() {
  local current original
  current=$(current_boot_behaviour)
  original=$(state_get original_boot_behaviour)

  # Remember how the Pi booted before this script first changed it, so that
  # --uninstall can put it back.
  if [[ -z $original ]]; then
    if [[ $(state_get autologin_enabled_by_script) == 1 ]]; then
      original=B1   # installed by an older version of this script
    else
      original=$current
    fi
    state_set original_boot_behaviour "$original"
  fi

  step "Setting up auto-start"
  if ! command -v raspi-config > /dev/null 2>&1; then
    warn "raspi-config not found, so automatic login could not be enabled."
    warn "Moonlight will still start when you log in on the TV."
    return 0
  fi
  if [[ $current == B2 ]]; then
    info "The Pi already boots to the console with automatic login."
  else
    sudo raspi-config nonint do_boot_behaviour B2
    ok "The Pi will now boot to the console with automatic login (was: $(boot_behaviour_name "$current"))"
  fi
  if [[ $original != B2 ]]; then
    state_set autologin_enabled_by_script 1
  fi
}

setup_bash_profile() {
  step "Updating ${BASH_PROFILE}"
  local created
  created=$(state_get created_bash_profile)
  if [[ ! -f $BASH_PROFILE ]]; then
    touch "$BASH_PROFILE"
    created=1
    state_set created_bash_profile 1
  else
    backup_file "$BASH_PROFILE"
  fi

  remove_block "$BASH_PROFILE"

  # Warn about older manual Moonlight settings outside our section.
  local leftovers
  leftovers=$(grep -nE 'QT_QPA_EGLFS_KMS_CONFIG|AUDIODEV|VK_DRIVER_FILES|PYROWAVE_PRECISION|moonlight' "$BASH_PROFILE" || true)
  if [[ -n $leftovers ]]; then
    warn "${BASH_PROFILE} already contains Moonlight-related lines that this script didn't add:"
    while IFS= read -r line; do info "  ${line}"; done <<<"$leftovers"
    warn "They may conflict with the new settings. Consider removing them."
  fi

  {
    echo "$MARK_BEGIN"
    echo "# Managed by moonlight-pi-setup. Re-run the script to repair it, or run it"
    echo "# with --uninstall to remove it."
    if [[ $created == 1 ]]; then
      # shellcheck disable=SC2016
      echo '[ -f "$HOME/.profile" ] && . "$HOME/.profile"'
    fi
    # shellcheck disable=SC2016
    echo 'export QT_QPA_EGLFS_KMS_CONFIG="$HOME/.config/moonlight-pi-setup/eglfs.json"'
    echo 'export AUDIODEV=default'
    cat <<EOF
# Send audio to whichever HDMI port has a screen connected (HDMI 0 is checked
# first). Falls back to HDMI ${HDMI_PORT}, the port used during setup.
moonlight_hdmi_card() {
  for port in 1 2; do
    for status in /sys/class/drm/card*-HDMI-A-\$port/status; do
      if [ "\$(cat "\$status" 2>/dev/null)" = "connected" ]; then
        echo "vc4hdmi\$((port - 1))"; return
      fi
    done
  done
  echo "vc4hdmi${HDMI_PORT}"
}
export MOONLIGHT_HDMI_CARD="\$(moonlight_hdmi_card)"
EOF
    # Use the ALSA settings above, even if an audio server such as PipeWire is installed.
    echo 'export SDL_AUDIODRIVER=alsa'
    cat <<'EOF'
# Start Moonlight on the TV (tty1 only, so SSH logins are not affected). When it
# closes, the menu opens (controllers, Wi-Fi, settings, power). At boot the menu
# opens first if the Pi is offline, has no controller, or needs its Quick setup.
# Menu exit codes: 0 start Moonlight, 10 command line, 20 restarting.
if [ "$(tty)" = "/dev/tty1" ]; then
  moonlight-menu --boot 2>> /tmp/moonlight-menu.log
  rc=$?
  while true; do
    case $rc in
      0)
        if command -v moonlight_hdmi_card > /dev/null 2>&1; then
          export MOONLIGHT_HDMI_CARD="$(moonlight_hdmi_card)"
        fi
        moonlight-qt > /tmp/moonlight.log 2>&1
        moonlight-menu 2>> /tmp/moonlight-menu.log
        rc=$?
        ;;
      10)
        echo "Type 'exit' to go back to Moonlight and the menu."
        break
        ;;
      20)
        sleep 60
        ;;
      *)
        echo "The menu couldn't start (see /tmp/moonlight-menu.log)."
        echo "Press any key within 5 seconds for a command line, or wait to start Moonlight..."
        if read -r -t 5 -n 1; then
          echo
          break
        fi
        rc=0
        ;;
    esac
  done
fi
EOF
    echo "$MARK_END"
  } >> "$BASH_PROFILE"
  ok "Saved Moonlight settings and auto-start"
}

# helper <command> [value]: change a setting with the settings helper (as root).
helper() {
  sudo "$SETTINGS_HELPER" "$@" 2>&1 | sed 's/^/    /'
}

