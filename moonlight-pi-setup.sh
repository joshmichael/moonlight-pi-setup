# Undo setup_menu.
remove_menu() {
  [[ -e $MENU_BIN || -d $LIB_DIR || -f $PHONE_SERVICE || -f $POLKIT_RULE || -f $SUDOERS_FILE ]] || return 0
  if [[ -f $PHONE_SERVICE ]]; then
    sudo systemctl stop "$PHONE_SERVICE_NAME" > /dev/null 2>&1 || true
    sudo rm -f "$PHONE_SERVICE"
    sudo systemctl daemon-reload
  fi
  sudo nmcli connection delete id moonlight-setup-hotspot > /dev/null 2>&1 || true
  sudo rm -f /etc/NetworkManager/dnsmasq-shared.d/moonlight-wifi-setup.conf
  sudo rm -f "$POLKIT_RULE" "$SUDOERS_FILE"
  if [[ -f $MENU_BIN ]] && grep -q "moonlight-pi-setup" "$MENU_BIN"; then
    sudo rm -f "$MENU_BIN"
  fi
  sudo rm -rf "$LIB_DIR" "$ROOT_STATE_DIR"
  ok "Removed the TV menu and its settings helper"
}

# The menu that opens on the TV when Moonlight closes (Bluetooth controllers,
# Wi-Fi including setup from a phone, settings, restart and shut down), and the
# settings helper that both the menu and this script use.
setup_menu() {
  step "Installing the TV menu and settings"
  sudo apt-get install -y "${MENU_PACKAGES[@]}"

  sudo install -d -m 755 "$LIB_DIR" "$MENU_DIR"
  local f
  for f in "${MENU_FILES[@]}"; do
    if [[ $f == *.py ]]; then
      sudo install -m 644 "$MENU_SRC/$f" "$MENU_DIR/$f"
    fi
  done
  # Replace the helper with a rename, so a copy that's running (the TV menu's
  # update runs this script through it) keeps reading the old file.
  sudo install -m 755 "$MENU_SRC/moonlight-settings.sh" "${SETTINGS_HELPER}.new"
  sudo mv -f "${SETTINGS_HELPER}.new" "$SETTINGS_HELPER"
  printf '#!/bin/sh\n# Installed by moonlight-pi-setup.\nexec python3 %s/moonlight_menu.py "$@"\n' "$MENU_DIR" \
    | sudo tee "$MENU_BIN" > /dev/null
  sudo chmod 755 "$MENU_BIN"

  # The menu changes settings through the helper. It's owned by root and only
  # accepts its own commands, so the user may run it without a password.
  local tmp
  tmp=$(mktemp)
  printf '%s\n%s ALL=(root) NOPASSWD: %s\n' \
    "# Installed by moonlight-pi-setup. Lets the TV menu change its settings without a password." \
    "$USER_NAME" "$SETTINGS_HELPER" > "$tmp"
  if sudo visudo -cqf "$tmp"; then
    sudo install -m 440 "$tmp" "$SUDOERS_FILE"
  else
    warn "Could not set up the sudoers rule, so the menu's Settings won't be able to change settings."
  fi
  rm -f "$tmp"
  helper init "$USER_NAME"

  # Phone Wi-Fi setup runs as root (it starts a hotspot and a web page) and is
  # started from the menu when needed.
  sudo tee "$PHONE_SERVICE" > /dev/null <<EOF
# Installed by moonlight-pi-setup.
[Unit]
Description=Moonlight Pi phone Wi-Fi setup (temporary hotspot and setup page)
Requires=NetworkManager.service
After=NetworkManager.service

[Service]
Type=simple
ExecStart=/usr/bin/python3 ${MENU_DIR}/wifi_setup.py
RuntimeDirectory=moonlight-wifi-setup
RuntimeDirectoryPreserve=yes
TimeoutStopSec=30
EOF

  # Let the menu (running as this user on the TV) change Wi-Fi, restart or shut
  # down, and start or stop phone setup, without asking for a password.
  sudo tee "$POLKIT_RULE" > /dev/null <<EOF
// Installed by moonlight-pi-setup. Lets ${USER_NAME} manage Wi-Fi, restart or shut down
// the Pi, and run phone Wi-Fi setup from the menu on the TV, without a password.
polkit.addRule(function(action, subject) {
    if (subject.user != "${USER_NAME}") {
        return polkit.Result.NOT_HANDLED;
    }
    var allowed = [
        "org.freedesktop.NetworkManager.network-control",
        "org.freedesktop.NetworkManager.enable-disable-wifi",
        "org.freedesktop.NetworkManager.wifi.scan",
        "org.freedesktop.NetworkManager.settings.modify.system",
        "org.freedesktop.NetworkManager.settings.modify.own",
        "org.freedesktop.login1.reboot",
        "org.freedesktop.login1.reboot-multiple-sessions",
        "org.freedesktop.login1.power-off",
        "org.freedesktop.login1.power-off-multiple-sessions"
    ];
    if (allowed.indexOf(action.id) >= 0) {
        return polkit.Result.YES;
    }
    if (action.id == "org.freedesktop.systemd1.manage-units" &&
        action.lookup("unit") == "${PHONE_SERVICE_NAME}" &&
        ["start", "stop", "restart"].indexOf(action.lookup("verb")) >= 0) {
        return polkit.Result.YES;
    }
    return polkit.Result.NOT_HANDLED;
});
EOF
  sudo chmod 644 "$POLKIT_RULE"
  sudo systemctl daemon-reload

  if [[ -n $WIFI_COUNTRY ]]; then
    helper wifi-country "$WIFI_COUNTRY" || warn "Could not set the Wi-Fi country. Set it later on the TV, in Settings."
  fi
  ok "When Moonlight closes, a menu for controllers, Wi-Fi, settings and power opens"
  info "To get to it from Moonlight's main screen, press B (or Esc) and confirm quitting."
}

# Keep a copy of this script so --uninstall works even if it was run with curl | bash.
save_script_copy() {
  local src="${BASH_SOURCE[0]:-}"
  if [[ -n $src && -f $src ]]; then
    if [[ $(readlink -f "$src") != $(readlink -f "$SAVED_SCRIPT" 2>/dev/null || true) ]]; then
      cp "$src" "$SAVED_SCRIPT"
    fi
  elif ! curl -fsSL "$RAW_SCRIPT_URL" -o "$SAVED_SCRIPT"; then
    warn "Could not save a copy of this script for uninstalling. Download it again from ${REPO_URL} if needed."
    return 0
  fi
  chmod +x "$SAVED_SCRIPT"
}

finish_install() {
  save_script_copy
  state_set version "$SCRIPT_VERSION"
  if (( FORCE )); then
    state_set forced 1
  fi
  # The settings are read from the Pi itself now, and the settings helper keeps
  # its own records (older versions saved all of these here).
  local key
  for key in audio_mode autostart quiet_boot quit_on_shutdown wifi_powersave_off usb_handoff menu \
             quiet_tokens_added vh_disabled_by_handoff; do
    state_unset "$key"
  done
  if (( FIRST_INSTALL )); then
    state_set quick_setup 1
  fi

  step "All done"
  if (( FIRST_INSTALL )); then
    info "After the restart, Quick setup on the TV asks about your speakers and a few other"
    info "settings. Change them any time in the menu's Settings (quit Moonlight to get there)."
    echo
  fi
  info "Recommended Moonlight settings (in Moonlight's settings screen):"
  info "  - Video codec:  HEVC (H.265)"
  info "  - Resolution:   match your TV, or 1440p / 1080p"
  info "  - Frame rate:   60 FPS"
  info "  - Bitrate:      around 50-100 Mbit/s on wired Ethernet"
  info "  - V-Sync:       on (off saves a few ms, but may cause tearing)"
  info "  - Audio:        set for you to match your speakers (for surround, set Windows to"
  info "                  the same speaker setup for the stream)"
  echo
  info "On your gaming PC you need a streaming host: Sunshine, Apollo or Vibepollo."
  if (( OPT_VIRTUALHERE || OPT_TAILSCALE )) || virtualhere_installed || command -v tailscale > /dev/null 2>&1; then
    echo
    info "Then set up the PC to match: open PowerShell on the gaming PC and paste:"
    info "  irm ${PC_SCRIPT_URL} | iex"
    info "It sets up the VirtualHere client (downloads it, starts it with Windows, and"
    info "makes it find the Pi quickly) and can install Tailscale."
  fi
  if (( OPT_TAILSCALE )); then
    info "Tailscale: away from home, add the PC in Moonlight using its Tailscale"
    info "address (100.x.x.x) and lower the bitrate."
  fi
  if (( OPT_VIRTUALHERE )) || virtualhere_installed; then
    info "VirtualHere: in the client on your PC, right-click each device that should move"
    info "to the PC and choose Auto-Use Device or Auto-Use Port."
    if (( OPT_USB_HANDOFF )); then
      info "The Pi's devices only appear there while you're streaming, so start a stream first."
    fi
  fi
  echo
  info "Moonlight log (after reboot): /tmp/moonlight.log"
  info "This run's log:               ${LOG_FILE}"
  info "To undo these changes:        ${SAVED_SCRIPT} --uninstall"
  echo
  if (( UNATTENDED )); then
    ok "Updated to version ${SCRIPT_VERSION}"
    return 0
  fi
  info "A reboot is needed for the new group membership and auto-start to take effect."
  if ask_yes_no "    Reboot now?" y; then
    sudo reboot
  else
    info "Reboot later with: sudo reboot"
  fi
}

# ---------------------------------------------------------------------------
# Uninstall
# ---------------------------------------------------------------------------
do_uninstall() {
  step "Uninstalling moonlight-pi-setup"
  if [[ $EUID -eq 0 ]]; then
    die "Please run --uninstall as your normal user (without sudo)."
  fi
  if [[ ! -f $STATE_FILE ]]; then
    warn "No record of a previous install was found in ${STATE_DIR}."
    ask_yes_no "    Try to remove the settings anyway?" n || exit 0
  fi
  # Only prompt for a password if sudo actually needs one.
  sudo -n true 2>/dev/null || sudo -v || die "Could not get administrator access."

  ask_yes_no "    Remove the settings this script added?" y || exit 0

  # ~/.bash_profile
  if [[ -f $BASH_PROFILE ]]; then
    remove_block "$BASH_PROFILE"
    if [[ $(state_get created_bash_profile) == 1 ]] && ! grep -q '[^[:space:]]' "$BASH_PROFILE"; then
      rm -f "$BASH_PROFILE"
      ok "Removed ${BASH_PROFILE}"
    else
      ok "Removed Moonlight settings from ${BASH_PROFILE}"
    fi
  fi

  # ~/.asoundrc
  remove_asoundrc

  # Display config
  if [[ -d $CONFIG_DIR ]]; then
    rm -rf "$CONFIG_DIR"
    ok "Removed ${CONFIG_DIR}"
  fi

  # Network tuning
  if [[ -f $SYSCTL_FILE ]]; then
    sudo rm -f "$SYSCTL_FILE"
    ok "Removed ${SYSCTL_FILE} (takes effect after a reboot)"
  fi

  # Boot behaviour: put back how the Pi booted before (a console login, or the
  # desktop if this was installed on the desktop version with --force)
  if [[ $(state_get autologin_enabled_by_script) == 1 ]] && command -v raspi-config > /dev/null 2>&1; then
    local original current
    original=$(state_get original_boot_behaviour)
    original=${original:-B1}
    current=$(current_boot_behaviour)
    if [[ $current != "$original" ]]; then
      sudo raspi-config nonint do_boot_behaviour "$original"
    fi
    case "$original" in
      B3|B4) ok "The Pi will boot to the desktop again" ;;
      *)     ok "Turned off automatic console login" ;;
    esac
  fi

  # Settings, undone with the settings helper: the installed one, or a fresh
  # copy for installs from before it existed.
  local h=$SETTINGS_HELPER ts_by_script
  if [[ ! -x $h ]]; then
    fetch_menu_files
    h="${MENU_SRC}/moonlight-settings.sh"
  fi
  ts_by_script=$(state_get tailscale_installed_by_script)
  if grep -qs '^tailscale_installed_by_script=1' "${ROOT_STATE_DIR}/state"; then
    ts_by_script=1
  fi
  sudo bash "$h" init "$USER_NAME" > /dev/null
  if [[ -f $NM_WIFI_CONF ]]; then
    sudo bash "$h" wifi-powersave on | sed 's/^/    /'
  fi
  sudo bash "$h" quiet-boot off | sed 's/^/    /'
  if [[ -f $QUIT_SERVICE || -f $QUIT_HELPER ]]; then
    sudo bash "$h" quit-on-shutdown off | sed 's/^/    /'
  fi
  if [[ -f $HANDOFF_SERVICE || -f $HANDOFF_HELPER ]]; then
    sudo bash "$h" usb-handoff off | sed 's/^/    /'
  fi

  # TV menu and settings helper
  remove_menu

  # Optional software
  if package_installed moonlight-qt && ask_yes_no "    Also uninstall Moonlight?" n; then
    sudo apt-get remove -y moonlight-qt
    if [[ $(state_get moonlight_repo_added) == 1 ]]; then
      sudo rm -f /etc/apt/sources.list.d/*moonlight-game-streaming*
      sudo rm -f /usr/share/keyrings/*moonlight-game-streaming*
      ok "Removed the Moonlight package repository"
    fi
  fi
  if [[ $ts_by_script == 1 ]] && ask_yes_no "    Also uninstall Tailscale?" n; then
    sudo tailscale down || true
    sudo apt-get remove -y tailscale || warn "Could not remove Tailscale."
  fi
  if [[ $(state_get virtualhere_installed_by_script) == 1 ]] && ask_yes_no "    Also uninstall VirtualHere?" n; then
    curl -fsSL "$VH_UNINSTALL_SCRIPT" | sudo sh || warn "Could not remove VirtualHere."
  fi

  # Forget the settings, but remember the software this script installed that is
  # still there, so a later --uninstall (after reinstalling) can still remove it.
  local kept=""
  if [[ $(state_get moonlight_repo_added) == 1 ]] && package_installed moonlight-qt; then
    kept+=$'moonlight_repo_added=1\n'
  fi
  if [[ $ts_by_script == 1 ]] && command -v tailscale > /dev/null 2>&1; then
    kept+=$'tailscale_installed_by_script=1\n'
  fi
  if [[ $(state_get virtualhere_installed_by_script) == 1 ]] && virtualhere_installed; then
    kept+=$'virtualhere_installed_by_script=1\n'
  fi
  if [[ -n $kept ]]; then
    printf '%s' "$kept" > "$STATE_FILE"
  else
    rm -f "$STATE_FILE"
  fi
  echo
  info "Backups of the files this script changed are kept in: ${BACKUP_DIR}"
  info "Your user was left in the video, render, input and audio groups (this is harmless)."
  if ask_yes_no "    Reboot now to finish?" y; then
    sudo reboot
  fi
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
usage() {
  cat <<EOF
moonlight-pi-setup ${SCRIPT_VERSION}

Sets up a Raspberry Pi 5 running Raspberry Pi OS Lite (64-bit, Trixie) as a
Moonlight game-streaming client.

Usage: $0 [option]

  (no option)    Install, or re-run to update or repair (your settings are kept;
                 change them on the TV, in the menu's Settings)
  --uninstall    Undo the changes this script made
  --force        Skip the hardware and OS checks, for example to install on
                 the desktop version of Raspberry Pi OS (unsupported)
  --unattended   No questions, keep everything as it is (used by the TV menu's
                 updates)
  --help         Show this help
  --version      Show the version

More information: ${REPO_URL}
EOF
}

main() {
  local mode="install"
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --uninstall) mode="uninstall" ;;
      --force)     FORCE=1 ;;
      --unattended) UNATTENDED=1 ;;
      --help|-h)   usage; exit 0 ;;
      --version)   echo "$SCRIPT_VERSION"; exit 0 ;;
      *)           usage; exit 1 ;;
    esac
    shift
  done

  mkdir -p "$STATE_DIR"
  LOG_FILE="${STATE_DIR}/${mode}-$(date +%Y%m%d-%H%M%S).log"
  exec > >(tee -a "$LOG_FILE") 2>&1

  printf '%sMoonlight Pi Setup %s%s\n' "$C_BOLD" "$SCRIPT_VERSION" "$C_RESET"

  if [[ $mode == "uninstall" ]]; then
    do_uninstall
    exit 0
  fi

  preflight
  fetch_menu_files
  load_settings
  ask_questions
  install_base_packages
  install_moonlight
  setup_groups
  setup_display
  setup_menu
  setup_audio
  setup_network
  setup_autologin
  setup_bash_profile
  setup_quiet_boot
  setup_quit_on_shutdown
  install_tailscale
  install_virtualhere
  setup_usb_handoff
  finish_install
}

